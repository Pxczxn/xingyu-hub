-- V048: 社区公约里"治理中心"这句指向一个并不存在的落地页。
--
-- 背景：V021 种子的 community-rules 正文写着
--   「举报与申诉机制可在治理中心查看。」
-- 但产品里**没有**"治理中心"这个页面（Governance Audit 结论：全站没有任何
-- 指向治理中心的入口，也没有这个路由）。用户点不到、也找不到，属于 UI 自述与
-- 产品不符的虚假文案。
--
-- 本轮 Contract Recovery 把治理真正接回产品后，用户实际拥有两件事：
--   - 我的举报（/reports）
--   - 我的申诉（/appeals）
-- 所以这句话应指到真实路径。
--
-- 幂等与安全：
--   * 只匹配**种子原文**（WHERE 里带完整旧串）。若运营已经把这段正文改写，
--     本迁移不会覆盖他们写的内容（重跑也是 no-op）。
--   * 只改 body，不动 id/slug/status/published_at。
--   * 迁移文件必须是 LF 行尾（LegacyMigrationChecksumsTest 强制）。

UPDATE `guide_page`
SET `body` = '请尊重他人、文明交流，不发布违法违规内容。举报与申诉可在「我的举报」与「我的申诉」中查看与跟进。'
WHERE `id` = '01900000-0000-7000-8000-000000000302'
  AND `body` = '请尊重他人、文明交流，不发布违法违规内容。举报与申诉机制可在治理中心查看。';
